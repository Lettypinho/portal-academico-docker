// =========================================================
// IR PARA INSTITUIÇÕES
// =========================================================

function irParaInstituicoes() {

    if (
        typeof abrirSecao ===
        "function"
    ) {

        abrirSecao(
            "universidades"
        );


        window.scrollTo({
            top:
                0,

            behavior:
                "smooth"
        });


        return;
    }


    const botaoMenu =
        document.querySelector(
            '[data-section="universidades"]'
        );


    if (botaoMenu) {

        botaoMenu.click();
    }
}


// =========================================================
// ABRIR ARTIGO
// =========================================================

function abrirArtigoSia(
    id
) {

    const artigo =
        artigosSia[id];


    if (!artigo) {
        return;
    }


    const modal =
        document.getElementById(
            "home-article-modal"
        );


    const categoria =
        document.getElementById(
            "home-article-modal-category"
        );


    const titulo =
        document.getElementById(
            "home-article-modal-title"
        );


    const corpo =
        document.getElementById(
            "home-article-modal-body"
        );


    if (
        !modal ||
        !categoria ||
        !titulo ||
        !corpo
    ) {

        return;
    }


    categoria.textContent =
        artigo.categoria;


    titulo.textContent =
        artigo.titulo;


    corpo.innerHTML =
        artigo.conteudo;


    modal.classList.remove(
        "hidden"
    );


    modal.setAttribute(
        "aria-hidden",
        "false"
    );


    document.body.style.overflow =
        "hidden";
}


// =========================================================
// FECHAR ARTIGO
// =========================================================

function fecharArtigoSia() {

    const modal =
        document.getElementById(
            "home-article-modal"
        );


    if (!modal) {
        return;
    }


    modal.classList.add(
        "hidden"
    );


    modal.setAttribute(
        "aria-hidden",
        "true"
    );


    document.body.style.overflow =
        "";
}


// =========================================================
// EVENTOS
// =========================================================

const btnInstituicoes =
    document.getElementById(
        "btn-ir-instituicoes"
    );


if (btnInstituicoes) {

    btnInstituicoes.addEventListener(
        "click",
        irParaInstituicoes
    );
}


document
    .querySelectorAll(
        "[data-abrir-artigo]"
    )
    .forEach(
        botao => {

            botao.addEventListener(
                "click",
                () => {

                    abrirArtigoSia(
                        botao.dataset
                            .abrirArtigo
                    );
                }
            );
        }
    );


const btnFecharArtigo =
    document.getElementById(
        "btn-fechar-artigo"
    );


if (btnFecharArtigo) {

    btnFecharArtigo.addEventListener(
        "click",
        fecharArtigoSia
    );
}


const modalBackdrop =
    document.querySelector(
        ".home-article-modal-backdrop"
    );


if (modalBackdrop) {

    modalBackdrop.addEventListener(
        "click",
        fecharArtigoSia
    );
}


document.addEventListener(
    "keydown",
    event => {

        if (
            event.key ===
            "Escape"
        ) {

            fecharArtigoSia();
        }
    }
);